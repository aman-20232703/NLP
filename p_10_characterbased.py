import numpy as np
import tensorflow as tf

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding, LSTM, Dense
from tensorflow.keras.losses import SparseCategoricalCrossentropy

# Download Shakespeare text dataset

path = tf.keras.utils.get_file(
    'shakespeare.txt',
    'https://storage.googleapis.com/download.tensorflow.org/data/shakespeare.txt'

)
# Read the text file

text = open(path, 'rb').read().decode(encoding='utf-8')

print("Length of text:", len(text))
print(text[:500])

# Find all unique characters

vocabulary = sorted(set(text))

# Count unique characters

vocab_size = len(vocabulary)

print('vocabulary:',vocabulary)
print("Total unique characters:", vocab_size)

# Create character-to-index dictionary
char_to_index = {}
for index, char in enumerate(vocabulary):
  char_to_index[char] = index
print("char_to_index:\n",char_to_index)

# Create index-to-character dictionary
index_to_char = np.array(vocabulary)
print("\n index_to_char:\n",index_to_char)

# Convert complete text into numerical values
temp_list = []
for char in text:
  index = char_to_index[char]
  temp_list.append(index)
text_as_int = np.array(temp_list)


print("\n Original text:", text[:20])
print("\n Numerical representation:", text_as_int[:20])

# Define sequence length

sequence_length = 100

# Create dataset from numerical text

char_dataset = tf.data.Dataset.from_tensor_slices(
    text_as_int
)
print(char_dataset)
# Create sequences of 101 characters

sequences = char_dataset.batch(
    sequence_length + 1,
    drop_remainder=True
)
print(sequences)

# Split input and target
def split_input_target(sequence):
    input_text = sequence[:-1]
    target_text = sequence[1:]

    return input_text, target_text

dataset = sequences.map(split_input_target)

print("Dataset created successfully!")

# Set batch size

BATCH_SIZE = 64

# Shuffle and batch the dataset

dataset = (
    dataset.shuffle(10000).batch(BATCH_SIZE, drop_remainder=True)
)

print("Training batches prepared!")

model = Sequential([

    # Convert character IDs into vectors
    Embedding(
        input_dim=vocab_size,
        output_dim=128
    ),

    # Learn character sequence patterns
    LSTM(
        256,
        return_sequences=True
    ),

    # Predict the next character
    Dense(vocab_size)
])

# Display model architecture

model.summary()

model.compile(
    optimizer='adam',
    loss=SparseCategoricalCrossentropy(
        from_logits=True
    ),
    metrics=['accuracy']
)

print("Model compiled successfully!")

# Train the character prediction model

EPOCHS = 10

history = model.fit(
    dataset,
    epochs=EPOCHS
)

def predict_next_character(input_text):

    # Convert input characters into integer IDs
    input_ids = [
        char_to_index[char] for char in input_text
    ]

    # Convert into NumPy array
    input_ids = np.array([input_ids])

    # Predict next character
    predictions = model.predict(input_ids, verbose=0)

    # Get scores for the last character position
    predicted_id = np.argmax(predictions[0, -1])

    # Convert predicted ID into character
    return index_to_char[predicted_id]


# Test the model

input_text = "Shakespear"

next_char = predict_next_character(input_text)

print("Input sequence:", input_text)
print("Predicted next character:", next_char)

def generate_text(start_string, num_chars=200):

    generated_text = start_string

    for i in range(num_chars):

        # Convert current text into numerical IDs
        input_ids = [
            char_to_index[char]
            for char in generated_text[-100:]
        ]

        input_ids = np.array([input_ids])

        # Get model predictions
        predictions = model.predict(
            input_ids,
            verbose=0
        )

        # Get prediction scores for the last position
        predicted_id = np.argmax(predictions[0, -1])

        # Convert ID into character
        predicted_char = index_to_char[predicted_id]

        # Add predicted character
        generated_text += predicted_char

    return generated_text


# Generate text

generated = generate_text(
    start_string="ROMEO: ",
    num_chars=200
)

print(generated)