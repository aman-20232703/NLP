# 1. Email usernames: Matches the part before the '@' in a standard email pattern.
email_username_pattern=re.compile(r"(\b[A-Za-z0-9._%+-]+)@")
for match in email_username_pattern.finditer(text):
  print(match.group(1))

# 2. Hashtags: Matches the '#' symbol followed by one or more word characters.
hastag_pattern=re.compile(r"#(\w+)\b")
for match in hastag_pattern.finditer(text):
  print(match.group(1))

# 3. Dates: A general pattern to match common date formats (e.g., YYYY-MM-DD, MM/DD/YY, Mar 20, 2009).
date_pattern= re.compile( r'\b(?:'
    r'(?:\d{1,2}(?:st|nd|rd|th)?[-/\s]+)?'
    r'(?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|'
    r'Jul(?:y)?|Aug(?:ust)?|Sep(?:tember)?|Oct(?:ober)?|'
    r'Nov(?:ember)?|Dec(?:ember)?)'
    r'(?:[-/\s,]+\d{1,2}(?:st|nd|rd|th)?)?'
    r'(?:[-/\s,]+\d{2,4})?'
    r')\b',re.IGNORECASE)
for match in date_pattern.finditer(text):
  print(match.group(0).strip())

# 4. Phone Numbers: A pattern to match common phone number formats (e.g., +1-555-555-5555, (555) 555-5555, 555.555.5555).
phone_pattern = re.compile(r"\b\+?\d{1,3}?[-.\s]?\(?\d{3}\)?[-.\s]?\d{3}[-.\s]?\d{4}\b")
phone_numbers = [match.group(0).strip() for match in phone_pattern.finditer(text)]
