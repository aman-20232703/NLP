# Using gutenberg.raw() to get the full string for custom processing
raw_text = gutenberg.raw('carroll-alice.txt')

def list_common_words(text, num_words=10):

  # Get the set of English stopwords
  stop_words = set(stopwords.words('english'))
  # print(stop_words)
  # print(text)

  # convert text to the lowercase and remove punctuation
  text = text.lower()
  text = text.translate(str.maketrans('','',string.punctuation))
  # print(text)

  # split text into words
  words = text.split()
  # print(words)

  # filetered out stopwords and single characters words
  filtered_words = []
  for word in words:
    if word not in stop_words:
      if len(word)>1:
        filtered_words.append(word)
  # print(filtered_words)

  # count frequency of each words
  word_counts = Counter(filtered_words)
  # print(word_counts)

  # return the moct common words
  return word_counts.most_common(num_words)

print("Most common words (excluding stopwords):")

list_common_words(raw_text, num_words=20)