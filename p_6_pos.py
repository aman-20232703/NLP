import pandas as pd
import nltk
import string
from collections import Counter

# Download the necessary NLTK resource if not already downloaded
nltk.download("averaged_perceptron_tagger_eng")
nltk.download("punkt_tab")

filename = 'input_text.txt'
#Create a dummy input file named 'input_text.txt' with some content
with open(filename, 'w') as f:
  f.write("Once upon a time, 3 little bakers lived in a small town.They woke up at 5 o'clock in the morning every single day.They baked 12 loaves of warm bread.")

#Reads a text file
try:
  with open(filename, 'r', encoding='utf-8') as f:
    text = f.read()
except IOError as e:
    print(f"Error reading file: {e}")

# remove punctuation for better tagging/counting)
text = text.translate(str.maketrans('', '', string.punctuation))

# Tokenize the text into words
words = nltk.word_tokenize(text)
words

# Perform POS tagging
pos_tags = nltk.pos_tag(words)
pos_tags

# 1. Extract all nouns
# nouns = [word for word, pos in pos_tags if pos.startswith('NN')]

nouns = []
for word, pos in pos_tags:
 if pos.startswith('NN'):
   nouns.append(word)
nouns

# 2. Create a dictionary with frequency of all parts of speech
tag_frequencies = Counter(tag for word, tag in pos_tags)
tag_frequencies

# 3. Print the results

print("nouns:", nouns)
print("Parts of Speech Frequency Dictionary:", dict(tag_frequencies))