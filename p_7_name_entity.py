import spacy

# loading pre-trained english model
try:
  nlp =  spacy.load("en_core_web_sm")
except IOError:
  print("model not found. please run python spacy correctly")
  exit()

# collection of news headlines
news_headlines= [
    "US Suspends Cognizant's Green Card Filings Amid Visa Fraud Probe, While Apple Launches New Products",
    "TVK and Congress Join Hands Under New Banner as Vijay-Led Bloc Gets 'Secular Social Justice Victory Alliance' Tag",
    "Ben Shelton Stuns Carlos Alcaraz in Latest-Ever U.S. Open Finish"
]

# process each headline and extract each entities
for i, headline in enumerate(news_headlines):
  print(f"\nHeadline {i+1}: '{headline}'")

  doc = nlp(headline)
  print("***",doc.ents)
  if doc.ents:
    print("Entities found:")
    for ent in doc.ents:
      # print entity text, its label type and a brief explaination
      print(f"{ent.text} --> {ent.label_} ({spacy.explain(ent.label_)})")

  else:
    print("no name entities found")