# importing all important libraries and modules
import numpy as np
from tensorflow.keras.datasets import imdb
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding, GlobalAveragePooling1D, Dense, Dropout
from tensorflow.keras.preprocessing.sequence import pad_sequences

# max word for training imbdb datasets
max_word = 10000
(x_train, y_train), (x_test, y_test) = imdb.load_data(num_words=max_word)

# max input length - training and testing
max_len = 200
x_train = pad_sequences(x_train, maxlen=max_len)
x_test = pad_sequences(x_test, maxlen=max_len)

# building neural network
model = Sequential([  # Initialize a linear stack of layers for the neural network model
    Embedding(input_dim = max_word, output_dim = 128, input_length = max_len ), # Map word indices to 128-dimensional continuous vector embeddings
    GlobalAveragePooling1D(), # Reduce sequence dimensions by taking the average value across all token embeddings
    Dense(24, activation = 'relu'), # Fully connected hidden layer with 24 neurons and ReLU activation for non-linearity
    Dropout(0.2), # Randomly deactivate 20% of neurons during training to prevent overfitting
    Dense(1, activation = 'sigmoid') # Output layer with 1 neuron and Sigmoid activation to output a probability (0 to 1) for binary classification
])

model.compile(loss = 'binary_crossentropy', optimizer = 'adam', metrics = ['accuracy'])
model.fit(x_train, y_train, epochs=10, batch_size = 32,validation_data =(x_test, y_test) )
loss,accuracy = model.evaluate(x_test, y_test, verbose = 0)
#print(f'Test loss: {loss}, Test accuracy: {accuracy}')

model.compile(loss = 'binary_crossentropy', optimizer = 'adam', metrics = ['accuracy'])
history = model.fit(
    x_train, y_train,
    batch_size = 64,
    epochs=3,
    validation_data =(x_test, y_test)
)
loss,accuracy = model.evaluate(x_test, y_test, verbose = 1)
print(f'test accuracy: {accuracy*100:.2f}%')